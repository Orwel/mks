- **Tratamiento:** cualquier operación sobre datos personales, como la recolección, almacenamiento, uso, circulación o supresión.
- **Autorización:** consentimiento previo, expreso e informado del Titular.
- **Responsable:** quien decide sobre la base de datos y el tratamiento; en este caso, IKEBANA.
- **Encargado:** quien realiza el tratamiento por cuenta del Responsable.
- **Aviso de privacidad:** comunicación que informa al Titular sobre esta Política y las finalidades del tratamiento.

